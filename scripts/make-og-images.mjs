#!/usr/bin/env node
/**
 * Render the share images: og/<page path>.png, 1200 x 630, one per page that has its own (the app page in 26 languages, the price pages of
 * the 32 country pages in their language, the main Danish pages), and write functions/_og_manifest.js, which tells the Function which file a
 * page gets and what its og:image:alt says. The cards are drawn from the repo's own tables and screenshots by scripts/og-cards.mjs.
 *
 *   npm run og                       render everything, rewrite og/ and the manifest
 *   node scripts/make-og-images.mjs --only de      only the cards whose page path contains "de" (writes the files, not the manifest)
 *   node scripts/make-og-images.mjs --out /tmp/x   write the PNGs there instead (to look at a change before it touches og/)
 *
 * Needs Playwright (a devDependency: npm install) and a Chromium: the one Playwright installed, or the installed Google Chrome. No network, no
 * hotlinked font or image: Manrope is the Android app's font file in this repository (Latin, Latin Extended, Cyrillic, Greek; SIL OFL 1.1).
 * When ImageMagick is installed the PNGs are also reduced to a 256-colour palette (the cards are flat colour, a screenshot and shadows) if that
 * is needed to stay under the limit; the share crawlers of WhatsApp and Telegram drop images much over 300 KB, so the limit is 250 KB.
 *
 * Run it after changing a headline (DL_TEXT, PRIS_COUNTRIES), a screenshot or scripts/og-cards.mjs: test-og-images.mjs fails while an image is
 * older than what it is made from.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { cardSpecs, cardHtml, specHash, ROOT, W, H } from './og-cards.mjs';

export const LIMIT = 250 * 1024;
const args = process.argv.slice(2);
const opt = n => { const i = args.indexOf('--' + n); return i < 0 ? null : args[i + 1] ?? true; };
const only = opt('only'), outDir = opt('out');

const specs = (await cardSpecs()).filter(s => !only || s.key.includes(only));
if (!specs.length) { console.error('no card matches'); process.exit(1); }

let chromium;
try { ({ chromium } = createRequire(path.join(ROOT, 'package.json'))('playwright')); }
catch { console.error('Playwright is not installed: run `npm install` in the repository.'); process.exit(1); }
let browser;
const ARGS = ['--force-color-profile=srgb', '--disable-gpu'];   // the same pixels on every machine: sRGB, software raster
try { browser = await chromium.launch({ args: ARGS }); }
catch { browser = await chromium.launch({ channel: 'chrome', args: ARGS }); }   // no Playwright browser downloaded: use the installed Google Chrome

const hasMagick = (() => { try { execFileSync('magick', ['-version'], { stdio: 'ignore' }); return true; } catch { return false; } })();
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'og-'));
const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
const out = {};
const report = [];
for (const spec of specs) {
  const html = path.join(tmp, crypto.createHash('sha1').update(spec.key).digest('hex').slice(0, 10) + '.html');
  fs.writeFileSync(html, cardHtml(spec));
  await page.goto(pathToFileURL(html).href);
  await page.waitForSelector('html[data-ready="1"]');
  const info = await page.evaluate(() => ({ size: +document.documentElement.dataset.size, lines: +document.documentElement.dataset.lines }));
  const dest = path.join(outDir || path.join(ROOT, 'og'), spec.file.replace(/^\/og\//, ''));
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  await page.screenshot({ path: dest, type: 'png', clip: { x: 0, y: 0, width: W, height: H } });
  let bytes = fs.statSync(dest).size, note = '';
  if (bytes > LIMIT * 0.8 && hasMagick) {
    execFileSync('magick', [dest, '-dither', 'None', '-colors', '256', '-define', 'png:compression-level=9', dest]);
    bytes = fs.statSync(dest).size; note = ' (palette)';
  }
  report.push(`${spec.key.padEnd(44)} ${String(info.size).padStart(3)}px ${info.lines} lines ${String(Math.round(bytes / 1024)).padStart(4)} KB${note}`);
  if (bytes > LIMIT) report.push(`  !! ${spec.key} is over ${LIMIT / 1024} KB`);
  out[spec.key] = { f: spec.file, v: specHash(spec), alt: spec.alt };
}
await browser.close();
fs.rmSync(tmp, { recursive: true, force: true });
console.log(report.join('\n'));

if (!only && !outDir) {
  // Sorted by page path so the diff of a regeneration is the pages that changed.
  const keys = Object.keys(out).sort();
  const body = keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join('\n');
  fs.writeFileSync(path.join(ROOT, 'functions/_og_manifest.js'),
    `// GENERATED by \`npm run og\` (scripts/make-og-images.mjs, docs/og-images.md): which share image each page has (f = the file under /og, v = a hash of what it is\n`
    + `// drawn from, alt = its words in the page's language). A page that is not here has the generic /og-image.png. Do not edit by hand.\nexport const OG = {\n${body}\n};\n`);
  console.log(`\n${keys.length} images, functions/_og_manifest.js written`);
}
