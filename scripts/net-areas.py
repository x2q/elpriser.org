#!/usr/bin/env python3
"""Net company areas -> functions/_net-areas.js.

Reads Energistyrelsen's licence-boundary shapefile (https://ens.dk/forsyning-og-forbrug/bevilling-til-netvirksomhed,
"GIS-filer til kort"; ETRS89 / UTM 32N; one polygon per licence area with `Selsk_Nvn`) and writes, per net company the
site prices, the simplified boundary as GeoJSON geometry, its bounding box, and the largest single ring. The file is
the authoritative map; what we publish is a simplified copy (300 m tolerance, 4 decimals) for orientation only.

    python3 -m venv /tmp/netvenv && /tmp/netvenv/bin/pip install pyshp pyproj shapely
    /tmp/netvenv/bin/python scripts/net-areas.py path/to/Elnetsgranser_08_04_2026.shp 2026-04-08

A company is matched by its exact licence name — a fuzzy match once folded Radius and the small companies into LNet.
Licence holders we do not price are listed on stderr. The output is a generated file: do not edit it by hand.
"""
import json, sys, shapefile
from shapely.geometry import shape, mapping
from shapely.ops import unary_union
from shapely import transform as sh_transform
from pyproj import Transformer
import numpy as np

# site slug -> exact `Selsk_Nvn` values (a company can have several licence rows)
MAP = {
    'n1': ['N1'], 'trefor': ['TREFOR El-net'], 'trefor-ost': ['TREFOR El-Net Øst'], 'konstant': ['KONSTANT Net'],
    'dinel': ['Dinel'], 'vores-elnet': ['Vores Elnet'], 'ravdex': ['Ravdex'], 'rah-net': ['RAH Net'],
    'elvaerk': ['Netselskabet Elværk'], 'nord-energi': ['Nord Energi Net'], 'noe-net': ['NOE Net'],
    'elnet-midt': ['Elnet Midt'], 'flow-elnet': ['FLOW Elnet'], 'lnet': ['L-Net'], 'cerius': ['Cerius'], 'radius': ['Radius Elnet'],
}
shp, date = sys.argv[1], sys.argv[2]
sf = shapefile.Reader(shp, encoding='utf-8')
rows = [(sr.record.as_dict()['Selsk_Nvn'], shape(sr.shape.__geo_interface__)) for sr in sf.shapeRecords()]
tr = Transformer.from_crs(25832, 4326, always_xy=True)
def wgs(g):
    return sh_transform(g, lambda c: np.column_stack(tr.transform(c[:, 0], c[:, 1])))
def rnd(x): return round(x, 4)
def parts(g): return list(g.geoms) if hasattr(g, 'geoms') else [g]
def clean(g):
    g = g.buffer(0) if not g.is_valid else g
    return g

out = {}
for slug, names in MAP.items():
    found = [g for n, g in rows if n in names]
    assert found, f'{slug}: no licence row named {names}'
    g = clean(unary_union([clean(x) for x in found]))
    ps = parts(g); big = max(ps, key=lambda p: p.area)
    simple = wgs(g.simplify(300, preserve_topology=True))
    ring = wgs(big.simplify(600, preserve_topology=True)).exterior
    minx, miny, maxx, maxy = wgs(g).bounds
    out[slug] = {
        'areaKm2': round(g.area / 1e6, 1), 'parts': len(ps), 'largestShare': round(big.area / g.area, 3),
        'box': [rnd(miny), rnd(minx), rnd(maxy), rnd(maxx)],           # south, west, north, east
        'ring': [[rnd(y), rnd(x)] for x, y in ring.coords],            # [lat, lng], closed
        'geometry': json.loads(json.dumps(mapping(simple), separators=(',', ':'))),
    }
def r4(o):
    if isinstance(o, float): return rnd(o)
    if isinstance(o, (list, tuple)): return [r4(x) for x in o]
    if isinstance(o, dict): return {k: r4(v) for k, v in o.items()}
    return o
for v in out.values(): v['geometry'] = r4(v['geometry'])
used = {n for v in MAP.values() for n in v}
print('licence holders not priced:', sorted({n for n, _ in rows if n not in used}), file=sys.stderr)
src = {'name': 'Energistyrelsen: Kort over netvirksomheder og bevillingsgrænser (elnetgrænser)', 'date': date,
       'url': 'https://ens.dk/forsyning-og-forbrug/bevilling-til-netvirksomhed'}
js = ('// GENERATED by scripts/net-areas.py from Energistyrelsen\'s licence-boundary shapefile — do not edit by hand.\n'
      '// Simplified to 300 m: for orientation, not for navigation or legal use. The authoritative map is Energistyrelsen\'s.\n'
      f'export const NET_AREAS_SOURCE = {json.dumps(src, ensure_ascii=False)};\n'
      f'export const NET_AREAS = {json.dumps(out, ensure_ascii=False, separators=(",", ":"))};\n')
open('functions/_net-areas.js', 'w').write(js)
print(f'wrote functions/_net-areas.js, {len(js)//1024} KB', file=sys.stderr)
for s, v in out.items(): print(f"{s:12} {v['areaKm2']:8} km2 parts {v['parts']:3} largest {v['largestShare']:.2f} ring {len(v['ring']):4} pts", file=sys.stderr)
